-- Additive controls only: consumers construct ratios after summing the same populations.
SELECT location_id, business_date, generation_id,
  count(*) AS accepted_count,
  sum(CAST(gross_complete AS BIGINT)) AS gross_eligible_count,
  sum(CAST(discount_complete AS BIGINT)) AS discount_eligible_count,
  sum(CAST(rate_eligible AS BIGINT)) AS rate_eligible_count,
  sum(CAST(discount_complete AND has_positive_discount AS BIGINT)) AS positive_check_count,
  sum(CAST(NOT gross_complete AS BIGINT)) AS gross_incomplete_count,
  sum(CAST(NOT discount_complete AS BIGINT)) AS discount_incomplete_count,
  sum(CAST(NOT gross_complete AND NOT discount_complete AS BIGINT)) AS incomplete_both_count,
  sum(CAST(gross_complete AND gross_sales = 0 AS BIGINT)) AS zero_gross_count,
  sum(CAST(gross_complete AND gross_sales < 0 AS BIGINT)) AS negative_gross_count,
  sum(sold_line_count) AS sold_line_count,
  sum(application_count) AS application_count,
  sum(unknown_gross_count) AS unknown_gross_count,
  sum(unknown_discount_count) AS unknown_discount_count,
  sum(item_application_count) AS item_application_count,
  sum(check_application_count) AS check_application_count,
  sum(positive_application_count) AS positive_application_count,
  sum(negative_application_count) AS negative_application_count,
  sum(zero_application_count) AS zero_application_count,
  coalesce(sum(CAST(gross_known_subtotal AS DECIMAL(38,6))), raise_error('Gold daily gross overflow')) AS gross_known_subtotal,
  coalesce(sum(CAST(discount_known_subtotal AS DECIMAL(38,6))), raise_error('Gold daily discount overflow')) AS discount_known_subtotal,
  coalesce(sum(CAST(positive_discount_known_subtotal AS DECIMAL(38,6))), raise_error('Gold daily positive overflow')) AS positive_discount_known_subtotal,
  coalesce(sum(CAST(negative_discount_known_subtotal AS DECIMAL(38,6))), raise_error('Gold daily negative overflow')) AS negative_discount_known_subtotal,
  coalesce(sum(CAST(item_discount_known_subtotal AS DECIMAL(38,6))), raise_error('Gold daily item overflow')) AS item_discount_known_subtotal,
  coalesce(sum(CAST(check_discount_known_subtotal AS DECIMAL(38,6))), raise_error('Gold daily check overflow')) AS check_discount_known_subtotal,
  coalesce(sum(CAST(rate_gross_component AS DECIMAL(38,6))), raise_error('Gold daily rate gross overflow')) AS rate_gross_component,
  coalesce(sum(CAST(rate_discount_component AS DECIMAL(38,6))), raise_error('Gold daily rate discount overflow')) AS rate_discount_component,
  coalesce(sum(CAST(eligible_positive_amount AS DECIMAL(38,6))), raise_error('Gold daily eligible positive overflow')) AS eligible_positive_amount,
  coalesce(sum(CAST(CASE WHEN gross_complete THEN gross_sales ELSE 0 END AS DECIMAL(38,6))), raise_error('Gold daily eligible gross overflow')) AS gross_eligible_amount,
  coalesce(sum(CAST(CASE WHEN discount_complete THEN recorded_discount_amount ELSE 0 END AS DECIMAL(38,6))), raise_error('Gold daily eligible discount overflow')) AS discount_eligible_amount
FROM {{storage_schema}}.gold_check_facts
WHERE generation_id = {{generation_id_literal}}
GROUP BY location_id, business_date, generation_id
